"""Workflow states (architecture.md section 4), as a typed enum."""

from enum import Enum


class RunState(str, Enum):
    CREATED = "CREATED"
    VALIDATING_INPUT = "VALIDATING_INPUT"
    RETRIEVING_EVIDENCE = "RETRIEVING_EVIDENCE"
    NORMALIZING_EVIDENCE = "NORMALIZING_EVIDENCE"
    SCORING = "SCORING"
    DRAFTING_EXPLANATION = "DRAFTING_EXPLANATION"
    CRITIC_REVIEW = "CRITIC_REVIEW"
    REVISING = "REVISING"
    FINAL_VALIDATION = "FINAL_VALIDATION"
    ROBUSTNESS_ANALYSIS = "ROBUSTNESS_ANALYSIS"
    COMPLETED = "COMPLETED"
    COMPLETED_WITH_LIMITATIONS = "COMPLETED_WITH_LIMITATIONS"
    FAILED_RETRYABLE = "FAILED_RETRYABLE"
    FAILED_TERMINAL = "FAILED_TERMINAL"


TERMINAL_STATES = frozenset(
    {
        RunState.COMPLETED,
        RunState.COMPLETED_WITH_LIMITATIONS,
        RunState.FAILED_TERMINAL,
    }
)
